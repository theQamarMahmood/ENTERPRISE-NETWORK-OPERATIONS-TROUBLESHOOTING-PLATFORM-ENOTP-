import os
from pydantic_settings import BaseSettings

class Settings(BaseSettings):
    PROJECT_NAME: str = "ENOTP - Enterprise Network Operations & Troubleshooting Platform"
    API_V1_STR: str = "/api/v1"
    SECRET_KEY: str = os.getenv("ENOTP_SECRET_KEY", "super_secret_jwt_signing_key_change_me_in_production")
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 60 * 24 * 7  # 7 Days

    # Database Settings
    POSTGRES_USER: str = os.getenv("POSTGRES_USER", "postgres")
    POSTGRES_PASSWORD: str = os.getenv("POSTGRES_PASSWORD", "postgres")
    POSTGRES_SERVER: str = os.getenv("POSTGRES_SERVER", "localhost")
    POSTGRES_PORT: str = os.getenv("POSTGRES_PORT", "5432")
    POSTGRES_DB: str = os.getenv("POSTGRES_DB", "enotp")
    USE_SQLITE: bool = os.getenv("USE_SQLITE", "True").lower() == "true"
    
    @property
    def DATABASE_URL(self) -> str:
        if self.USE_SQLITE:
            return "sqlite+aiosqlite:///./enotp.db"
        return f"postgresql+asyncpg://{self.POSTGRES_USER}:{self.POSTGRES_PASSWORD}@{self.POSTGRES_SERVER}:{self.POSTGRES_PORT}/{self.POSTGRES_DB}"
    
    @property
    def SYNC_DATABASE_URL(self) -> str:
        if self.USE_SQLITE:
            return "sqlite:///./enotp.db"
        return f"postgresql://{self.POSTGRES_USER}:{self.POSTGRES_PASSWORD}@{self.POSTGRES_SERVER}:{self.POSTGRES_PORT}/{self.POSTGRES_DB}"

    # Redis and Celery Settings
    REDIS_HOST: str = os.getenv("REDIS_HOST", "localhost")
    REDIS_PORT: str = os.getenv("REDIS_PORT", "6379")
    
    @property
    def CELERY_BROKER_URL(self) -> str:
        return f"redis://{self.REDIS_HOST}:{self.REDIS_PORT}/0"
        
    @property
    def CELERY_RESULT_BACKEND(self) -> str:
        return f"redis://{self.REDIS_HOST}:{self.REDIS_PORT}/0"

    # Credentials Encryption Key (AES-256)
    # MUST be a 32-byte urlsafe base64-encoded key.
    # Generated by cryptography.fernet.Fernet.generate_key()
    ENCRYPTION_KEY: str = os.getenv("ENOTP_ENCRYPTION_KEY", "t-33VbWhYQ1NlK4R9M5dJkI4j8P0Z9C-gS11o94_u_g=")

    # Network Scanning Settings
    DEFAULT_DISCOVERY_SUBNETS: str = os.getenv("DEFAULT_DISCOVERY_SUBNETS", "192.168.1.0/24,10.0.0.0/24")
    SYSLOG_PORT: int = int(os.getenv("SYSLOG_PORT", "514"))
    NETFLOW_PORT: int = int(os.getenv("NETFLOW_PORT", "2055"))

    class Config:
        case_sensitive = True

settings = Settings()
